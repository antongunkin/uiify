import { createHash } from "node:crypto";
import { cp, lstat, readFile, rm } from "node:fs/promises";
import { join } from "node:path";

const START = /<!-- uiify:start version=(\S+) sha=([0-9a-f]{12}) [^\n]*?-->\r?\n/;
const END = /\r?\n<!-- uiify:end -->/;
const toLf = (text) => text.replace(/\r\n/g, "\n");

/** First 12 hex characters of the SHA-256 of `text`. */
function digest(text) {
  return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

/** The generated body: the fixed rules, a blank line, the catalog. */
export function sectionBody(rules, catalog) {
  return `${rules.trimEnd()}\n\n${catalog.trimEnd()}`;
}

/**
 * `body` between the markers. The start marker carries the package version and a hash of the
 * body, so a later edit of the body can be detected. The marker says the hash is of this block:
 * agents read different hashes in two files as a stale copy (M8 rounds 3–4).
 * @param {string} version
 * @param {string} body
 */
export function markedSection(version, body) {
  return `<!-- uiify:start version=${version} sha=${digest(body)} (hash of this block; each file has its own) — generated by @gunkin/uiify, do not edit; run sync-agents.mjs -->\n${body}\n<!-- uiify:end -->`;
}

/**
 * The marked section for the user's `AGENTS.md`, markers included.
 * @param {string} version
 * @param {string} rules
 * @param {string} catalog
 */
export function composeSection(version, rules, catalog) {
  return markedSection(version, sectionBody(rules, catalog));
}

/** Locate the section in `fileText`: marker data, body and the span to replace. */
function findSection(fileText) {
  const start = START.exec(fileText);
  if (!start) return null;
  const bodyStart = start.index + start[0].length;
  const end = END.exec(fileText.slice(bodyStart - 1));
  if (!end) return null;
  const endIndex = bodyStart - 1 + end.index;
  return {
    version: start[1],
    sha: start[2],
    marker: start[0].trimEnd(),
    body: toLf(fileText.slice(bodyStart, endIndex)),
    from: start.index,
    to: endIndex + end[0].length,
    crlf: start[0].endsWith("\r\n"),
  };
}

/**
 * `edited`: the body no longer matches the hash in its own marker. `outdated`: untouched, but the
 * version, text or marker wording differs from the installed package.
 * @param {string} fileText
 * @param {string} installedVersion
 * @param {string} installedBody the body as composed from the installed package (markers excluded)
 * @returns {{ state: "missing" | "current" | "outdated" | "edited"; fromVersion?: string }}
 */
export function classifySection(fileText, installedVersion, installedBody) {
  const found = findSection(fileText);
  if (!found) return { state: "missing" };
  if (digest(found.body) !== found.sha) return { state: "edited", fromVersion: found.version };
  if (
    found.version !== installedVersion ||
    found.body !== installedBody ||
    found.marker !== markedSection(installedVersion, installedBody).split("\n", 1)[0]
  ) {
    return { state: "outdated", fromVersion: found.version };
  }
  return { state: "current", fromVersion: found.version };
}

/**
 * Append the section after one blank line when there is none; otherwise replace only what lies
 * between (and including) the markers.
 * @param {string} fileText
 * @param {string} section
 */
export function upsertSection(fileText, section) {
  const found = findSection(fileText);
  if (found) {
    const next = found.crlf ? section.replace(/\n/g, "\r\n") : section;
    return `${fileText.slice(0, found.from)}${next}${fileText.slice(found.to)}`;
  }
  if (fileText === "") return `${section}\n`;
  const eol = fileText.includes("\r\n") ? "\r\n" : "\n";
  const block = eol === "\n" ? section : section.replace(/\n/g, eol);
  const text = fileText.endsWith("\n") ? fileText : `${fileText}${eol}`;
  return `${text}${eol}${block}${eol}`;
}

/**
 * State of the user's skill directory against the installed package's skill: `linked` (a symlink,
 * always current), `current`, `outdated` (a copy whose version.json differs) or `absent`.
 * @param {string} skillDir
 * @param {string} installedSkillDir
 * @returns {Promise<"linked" | "current" | "outdated" | "absent">}
 */
export async function skillState(skillDir, installedSkillDir) {
  let info;
  try {
    info = await lstat(skillDir);
  } catch (error) {
    if (error.code === "ENOENT") return "absent";
    throw error;
  }
  if (info.isSymbolicLink()) return "linked";
  const [have, want] = await Promise.all([skillStamp(skillDir), skillStamp(installedSkillDir)]);
  if (have === null || want === null) return "outdated";
  const key = have.sha !== undefined && want.sha !== undefined ? "sha" : "version";
  return have[key] !== undefined && have[key] === want[key] ? "current" : "outdated";
}

/** Replace a copied skill directory with the installed one. Never call this on a symlink. */
export async function refreshSkill(skillDir, installedSkillDir) {
  if ((await lstat(skillDir)).isSymbolicLink()) throw new Error(`${skillDir} is a link; it is never written to`);
  await rm(skillDir, { recursive: true, force: true });
  await cp(installedSkillDir, skillDir, { recursive: true });
}

async function skillStamp(directory) {
  try {
    return JSON.parse(await readFile(join(directory, "version.json"), "utf8"));
  } catch (error) {
    if (error.code === "ENOENT" || error instanceof SyntaxError) return null;
    throw error;
  }
}
