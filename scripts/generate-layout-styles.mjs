/** Generate finite native selectors and Tailwind sources from the same declaration tables. */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
import { build } from "esbuild";
import { format } from "oxfmt";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { outputFiles } = await build({
  stdin: {
    contents:
      'export * from "./src/core/layout/index.ts"; export * from "./src/styles/layout/declarations.ts"; export * from "./src/styles/layout/tailwind.ts";',
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  write: false,
  platform: "node",
  format: "esm",
});
const source = await import(
  `data:text/javascript;base64,${Buffer.from(outputFiles[0].contents).toString("base64")}`
);
const {
  layoutParts,
  layoutConditions,
  layoutBreakpoints,
  layoutAttributes,
  layoutAttributeName,
  layoutDefaultDeclarations,
  layoutDeclarations,
  layoutControlSelector,
  createLayoutTailwindManifest,
} = source;
function selector(kind) {
  const marker = layoutAttributes(kind, {});
  return Object.entries(marker)
    .map(([name, value]) => `[${name}="${value}"]`)
    .join("");
}
function rule(selectors, declarations, indent = "  ") {
  if (!Object.keys(declarations).length) return "";
  return `${indent}${selectors} {\n${Object.entries(declarations)
    .sort(([a], [b]) => Number(b.startsWith("--")) - Number(a.startsWith("--")))
    .map(
      ([property, value], index, entries) =>
        `${index > 0 && entries[index - 1][0].startsWith("--") && !property.startsWith("--") ? "\n" : ""}${indent}  ${property}: ${value};`,
    )
    .join("\n")}\n${indent}}\n`;
}
let css =
  "/* Generated by scripts/generate-layout-styles.mjs. Do not edit. */\n\n/* Normalized longhands preserve per-condition overlap semantics in both outputs. */\n/* stylelint-disable declaration-block-no-redundant-longhand-properties */\n@layer layout {\n";
for (const kind of layoutParts) css += rule(selector(kind), layoutDefaultDeclarations[kind]);
css += rule(`${selector("Stack")} > ${layoutControlSelector}`, { "max-inline-size": "none" });
for (const condition of layoutConditions) {
  for (const viewport of condition === "base" ? [false] : [false, true]) {
    const indent = condition === "base" ? "  " : "    ";
    if (condition !== "base")
      css += `\n  @${viewport ? "media" : "container"} (width >= ${layoutBreakpoints[condition]}) {\n`;
    // Group shared declaration sets by part marker, avoiding one repeated selector per part.
    const groups = new Map();
    for (const kind of layoutParts) {
      for (const [prop, values] of Object.entries(layoutDeclarations[kind])) {
        for (const [value, declarations] of Object.entries(values)) {
          if (
            condition !== "base" &&
            (prop === "container" || prop === "responsive" || prop === "level")
          )
            continue;
          const basis =
            condition === "base"
              ? ""
              : viewport
                ? '[data-responsive="viewport"]'
                : ':not([data-responsive="viewport"])';
          const key = JSON.stringify([prop, value, declarations]);
          if (!groups.has(key)) groups.set(key, { kinds: [], declarations, suffix: "" });
          const group = groups.get(key);
          group.kinds.push(kind);
          group.suffix = `${basis}[${layoutAttributeName(prop, condition)}="${value}"]`;
        }
      }
    }
    for (const { kinds, declarations, suffix } of groups.values()) {
      const markers = [...new Set(kinds.map(selector))];
      const subject = markers.length === 1 ? markers[0] : `:is(${markers.join(", ")})`;
      css += rule(`${subject}${suffix}`, declarations, indent);
    }
    const basis =
      condition === "base"
        ? ""
        : viewport
          ? '[data-responsive="viewport"]'
          : ':not([data-responsive="viewport"])';
    for (const direction of ["block", "inline"])
      css += rule(
        `${selector("Stack")}${basis}[${layoutAttributeName("direction", condition)}="${direction}"] > ${layoutControlSelector}`,
        { "max-inline-size": direction === "inline" ? "revert-layer" : "none" },
        indent,
      );
    if (condition !== "base") css += "  }\n";
  }
}
css += "}\n";
const manifest = `// Generated by scripts/generate-layout-styles.mjs. Do not edit.\nexport const layoutTailwindManifest: readonly string[] = ${JSON.stringify(createLayoutTailwindManifest(), null, 2)};\n`;
const files = [
  ["src/styles/layout.generated.css", css],
  ["src/styles/layout/tailwind-manifest.generated.ts", manifest],
];
for (const [path, contents] of files) {
  const formatted = await format(path, contents, {});
  if (formatted.errors.length) throw new Error(JSON.stringify(formatted.errors));
  if (process.argv.includes("--check")) {
    if ((await readFile(resolve(root, path), "utf8")) !== formatted.code)
      throw new Error(
        `${path} is stale; run node packages/uiify/scripts/generate-layout-styles.mjs --write`,
      );
  } else await writeFile(resolve(root, path), formatted.code);
}
// oxlint-disable-next-line no-console -- CLI result for the caller.
console.log(
  `Layout styles ${process.argv.includes("--check") ? "fresh" : "generated"}; ${createLayoutTailwindManifest().length} Tailwind classes.`,
);
